import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';

const root=new URL('../',import.meta.url);
const entries=execFileSync('git',['ls-files','--stage','-z'],{cwd:root,encoding:'utf8'}).split('\0')
  .filter(Boolean).map(entry=>{
    const split=entry.indexOf('\t');
    return [entry.slice(split+1),entry.slice(0,split).split(' ')[1]];
  }).filter(([path])=>path==='index.html'||path==='account-pages.css'||path==='art-credits.txt'||path==='THREE-LICENSE.txt'||path==='privacy/index.html'||path==='terms/index.html'||path==='three.min.mjs'||path==='lantern-hall/index.html'||path.startsWith('eclipse/'));
entries.sort(([left],[right])=>left.localeCompare(right,'en'));
// Use the indexed blobs so hashes match the deployed bytes on Windows too.
const data=execFileSync('git',['cat-file','--batch'],{cwd:root,input:entries.map(([,hash])=>hash+'\n').join(''),maxBuffer:128*1024*1024});
let offset=0;
const contents=new Map();
const files=entries.map(([path,hash])=>{
  const end=data.indexOf(10,offset);
  const [object,type,length]=data.toString('utf8',offset,end).split(' ');
  if(object!==hash||type!=='blob')throw new Error('No staged blob for '+path);
  offset=end+1+Number(length);
  const content=data.subarray(end+1,offset);
  contents.set(path,content);
  offset++;
  return [path,content.length,createHash('sha256').update(content).digest('base64')];
});
// Cache only the active application graph. Retired source studies remain in
// version control for history and are not part of the playable offline pack.
const active=new Set();
function visit(path){
  if(active.has(path))return;active.add(path);
  const content=contents.get(path);if(!content)throw new Error('Missing active module '+path);
  const directory=path.slice(0,path.lastIndexOf('/')+1);
  for(const match of content.toString('utf8').matchAll(/['"]((?:\.\.\/|\.\/)[^'"\n]*?\.mjs(?:\?[^'"\n]*)?)['"]/g)){
    const target=new URL(match[1].split('?')[0],'https://pack.invalid/'+directory).pathname.slice(1);
    visit(target);
  }
}
for(const root of ['eclipse/game.mjs','eclipse/offline.mjs'])visit(root);
const shipped=files.filter(([path])=>!path.startsWith('eclipse/review/')&&(!path.endsWith('.mjs')||active.has(path)));
const body=JSON.stringify(shipped);
const version=createHash('sha256').update(body).digest('hex').slice(0,20);
writeFileSync(new URL('offline-assets.js',root),'// Generated by tools/build-offline.mjs.\nconst offlineRelease={version:'+JSON.stringify(version)+',files:'+body+'};\n');
console.log(version+' · '+shipped.length+' files · '+shipped.reduce((n,file)=>n+file[1],0)+' bytes');
