import assert from 'node:assert/strict';
import * as T from '../three.min.mjs';
import {ModelReserve} from '../eclipse/model-reserve.mjs';

const scene=new T.Scene(),destroyed=[];
let builds=0;
const build=(world,entry,height)=>{
  builds++;
  const root=new T.Group(),bone=new T.Bone();
  bone.position.set(1,2,3);root.add(bone);world.add(root);
  root.add(new T.Mesh(new T.BoxGeometry(),new T.MeshBasicMaterial()));
  return {root,entry,scale:height/2,hitFlash:{value:0},bone,
    skin:{reset(){bone.userData.reset=true;}},aura:{reset(){root.userData.reset=true;}}};
};
const destroy=(world,rig)=>{world.remove(rig.root);destroyed.push(rig);};
const pool=new ModelReserve(scene,build,destroy,true);
const entry={id:'guardian',palette:[1,2,3,4]},spec={effect:'fire'};
const first=pool.take(entry,4,true,spec);
first.bone.rotation.x=2;first.bone.position.x=70;first.root.visible=false;
first.hitFlash.value=1;first.heading=3;
pool.release(first);
assert.equal(first.root.parent,null);
const second=pool.take(entry,8,true,spec);
assert.equal(second,first);
assert.equal(second.scale,4,'world height can change without rebuilding the rig');
assert.equal(second.hitFlash.value,0);
assert.equal(second.heading,undefined);
assert.equal(second.root.visible,true);
assert.ok(Math.abs(second.bone.rotation.x)<1e-12);
assert.equal(second.bone.position.x,1);
assert.equal(second.bone.userData.reset,true);
const twin=pool.take(entry,8,true,spec);
assert.notEqual(twin,second,'simultaneous bosses must own independent rigs');
assert.notEqual(twin.hitFlash,second.hitFlash);
assert.equal(builds,2);
pool.release(second);pool.release(twin);
assert.equal(pool.stats.count,2);
const different=pool.take({...entry,palette:[4,3,2,1]},4,true,spec);
assert.notEqual(different,first,'palette variants must not inherit a cached appearance');
pool.release(different);
pool.maxCount=1;
const trigger=pool.take({id:'trigger'},4,true,spec);
pool.release(trigger);
assert.equal(pool.stats.count,1);
assert.equal(pool.stats.evictions,3,'oldest detached rigs are released');
pool.limit=1;
const oversized=pool.take({id:'oversized'},4,true,spec);
pool.release(oversized);
assert.ok(destroyed.includes(oversized));
pool.clear();
assert.equal(pool.stats.bytes,0);assert.equal(pool.stats.count,0);
assert.equal(scene.children.length,0);
console.log('Rig reuse, reset, twin isolation, variant identity, height, eviction and disposal passed.');
