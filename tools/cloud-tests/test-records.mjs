import assert from 'node:assert/strict';
import {indexedDB} from 'fake-indexeddb';
import {RunStore,ActiveRunClock,better} from '../../eclipse/challenge-records.mjs';
const dbName='test-'+crypto.randomUUID(),store=new RunStore({indexedDB,name:dbName});
await store.ready;
const guests=await Promise.all(Array.from({length:8},()=>store.guest()));
assert.equal(new Set(guests).size,1,'simultaneous initialization shares one guest identity');
const guest=guests[0],id=crypto.randomUUID();
const start={difficulty:'vigil',weapon_id:'qilin',test_mode:false,practice:false,actor_id:guest,tab_id:'tab-a'};
await store.begin({...start,id});
await store.checkpoint(id,{floor:20,elapsed_ms:120000,kills:80,offline:true});
await store.checkpoint(id,{floor:35,elapsed_ms:220000,kills:120});
await store.checkpoint(id,{elapsed_ms:250000,kills:130,status:'failed'});
let [row]=await store.all(guest);
assert.equal(row.highest_floor,35);assert.equal(row.cleared_ms,220000);assert.equal(row.elapsed_ms,250000);
assert.equal(row.offline,true);assert.equal(row.result_status,'failed');
await store.checkpoint(id,{floor:100,elapsed_ms:350000,kills:140});
assert.equal((await store.all(guest))[0].highest_floor,35,'finished history is immutable');
await store.begin({...start,id:crypto.randomUUID(),test_mode:true});
await store.begin({...start,id:crypto.randomUUID(),practice:true});
assert.equal((await store.all(guest)).length,1,'test and practice runs never enter history/upload queue');
await store.claim(guest,'player-a');
assert.equal((await store.all(guest)).length,0);
assert.equal((await store.all('user:player-a')).length,1);
await store.claim(guest,'player-b');
assert.equal((await store.all('user:player-b')).length,0,'changing accounts cannot claim someone else’s runs');
row=(await store.all('user:player-a'))[0];
await store.acknowledge(id,row.revision-1);
assert.equal((await store.all('user:player-a'))[0].sync_state,'pending','stale acknowledgement cannot consume a newer write');
await store.acknowledge(id,row.revision);
assert.equal((await store.all('user:player-a'))[0].sync_state,'synced');
const active=crypto.randomUUID(),other=crypto.randomUUID();
await store.begin({...start,id:active});await store.begin({...start,id:other,tab_id:'other-tab'});
await store.recover('tab-a');
assert.equal((await store.all()).find(r=>r.id===active).result_status,'abandoned');
assert.equal((await store.all()).find(r=>r.id===other).result_status,'active','another tab’s battle must not be ended');
store.close();
const reopened=new RunStore({indexedDB,name:dbName});await reopened.ready;
assert.equal((await reopened.all()).length,3,'offline history survives a cold launch');
assert.equal((await reopened.all('user:player-a')).find(row=>row.id===id).sync_state,'synced');
reopened.close();
assert.equal(better({highest_floor:35,cleared_ms:220000},{highest_floor:20,cleared_ms:120000}),true);
assert.equal(better({highest_floor:35,cleared_ms:180000},{highest_floor:35,cleared_ms:220000}),true);
assert.equal(better({highest_floor:20,cleared_ms:100000},{highest_floor:35,cleared_ms:220000}),false);
const clock=new ActiveRunClock();
clock.tick(100,true);clock.tick(1100,true);clock.tick(1200,false);clock.tick(12000,false);clock.tick(13000,true);clock.tick(13500,true);
assert.equal(clock.milliseconds,1500,'menus and resume gaps do not count');
clock.tick(23500,true);assert.equal(clock.milliseconds,11500,'slow rendering must not make ranking time artificially shorter');
clock.pause();clock.tick(100000,true);assert.equal(clock.milliseconds,11500);
console.log('Offline persistence, best ordering, account ownership, test exclusions, retry races, multi-tab recovery and active clock passed.');
