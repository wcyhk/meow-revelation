import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const directory=process.argv[2];
if(!directory)throw new Error('Usage: node tools/import-00gamedevs.mjs <verified downloads directory>');
const output=new URL('../eclipse/vendor/00gamedevs/',import.meta.url);
const catalog=JSON.parse(readFileSync(path.join(directory,'catalog.v2.json'),'utf8'));
if(catalog.schemaVersion!==2)throw new Error('Unsupported catalog version');
const effects=catalog.assets.filter(asset=>asset.kind==='effect');
const digest=source=>createHash('sha256').update(source).digest('hex');
const clean=source=>source.replace(/[\t ]+$/gm,'');
const shared=new Map();
const entries=[];

function localImports(source){
  return source.replace(/(\/\*[\s\S]*?\*\/)|(^import\s+[^;]+?\bfrom\s+)["']([^"']+)["']/gm, (whole,comment,prefix,name)=>{
    if(comment)return whole;
    if(name==='three')return `${prefix}"../../../three.min.mjs"`;
    if(name==='three/addons/postprocessing/Pass.js')return `${prefix}"./pass.mjs"`;
    throw new Error(`Unrecognized dependency ${name}`);
  });
}

mkdirSync(output,{recursive:true});
for(const asset of effects){
  const {id,name,category,description,integration,parameters,load,download}=asset;
  if(!/^[a-z0-9-]+$/.test(id)||asset.license!=='MIT'||asset.dependencies.three!=='0.187.0'){
    throw new Error(`Unexpected asset metadata ${id}`);
  }
  const bytes=readFileSync(path.join(directory,`${id}.js`));
  if(bytes.length!==download.bytes||digest(bytes)!==download.sha256)throw new Error(`Mismatched original ${id}`);
  let source=localImports(bytes.toString('utf8'));
  const bundleStart=source.indexOf('var __vfxModule = (function(');
  const factory=source.match(/^const \w+ = __vfxModule\.\w+;$/m);
  const title=source.match(/^\/\*![\s\S]*?\*\//)?.[0];
  if(!title)throw new Error(`Missing original license ${id}`);
  if(bundleStart>=0&&factory&&source.length>100_000){
    const bundleEnd=factory.index;
    const bundle=source.slice(bundleStart,bundleEnd);
    const imports=source.slice(0,bundleStart).match(/^import .+;$/gm)??[];
    const runtime=imports.join('\n')+'\n'+bundle;
    const key=`runtime-${digest(runtime).slice(0,16)}`;
    if(!shared.has(key))shared.set(key,`${title}\n${runtime}\nexport {__vfxModule};\n`);
    source=`${source.slice(0,bundleStart)}import {__vfxModule} from './${key}.mjs';\n${source.slice(bundleEnd)}`;
  }
  writeFileSync(new URL(`${id}.mjs`,output),clean(source));
  entries.push({id,name,category,description,type:integration.type,playback:integration.playback,
    level:load.level,methods:integration.methods,parameters,sha256:download.sha256});
}
for(const [id,source] of shared)writeFileSync(new URL(`${id}.mjs`,output),clean(source));
const modules=entries.map(({id})=>`  '${id}':()=>import('./${id}.mjs'),`).join('\n');
writeFileSync(new URL('catalogue.mjs',output),
  `// Generated from 00GameDevs catalogue ${catalog.contentVersion}.\nexport const effects=${JSON.stringify(entries,null,2)};\nexport {loaders} from './loaders.mjs';\n`);
writeFileSync(new URL('loaders.mjs',output),`// Generated by tools/import-00gamedevs.mjs.\nexport const loaders={\n${modules}\n};\n`);
console.log(`${entries.length} SHA-256 checked effects · ${shared.size} shared runtimes`);
